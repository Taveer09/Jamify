import { expect, test } from '@playwright/test'
import type { Page } from '@playwright/test'

async function reviewWithoutAudio(page: Page, playlist?: string) {
  await page.route('**/demo/*.wav', (route) => route.abort())
  await page.goto('/demo')
  if (playlist) await page.getByRole('button', { name: new RegExp(playlist) }).click()
  await page.getByRole('button', { name: /Начать разбор/ }).click()
  await page.getByRole('button', { name: 'Продолжить без звука' }).click()
}

test('reload restores the exact card, decisions and undo history', async ({ page }) => {
  await reviewWithoutAudio(page)
  await page.getByRole('button', { name: 'Убрать', exact: false }).click()
  await page.getByRole('button', { name: 'Оставить', exact: false }).click()
  await expect(page.locator('.session-progress > span')).toContainText('3 / 6')
  const skipped = await page.locator('.track-details h2').innerText()
  await page.getByRole('button', { name: 'Пропустить', exact: true }).click()
  const next = await page.locator('.track-details h2').innerText()
  await expect(page.locator('.save-status')).toHaveText('Решения сохранены на этом устройстве')
  await page.reload()
  await page.getByRole('button', { name: /Начать разбор/ }).click()
  await expect(page.locator('.track-details h2')).toHaveText(next)
  await page.getByRole('button', { name: /Отменить решение/ }).click()
  await expect(page.locator('.track-details h2')).toHaveText(skipped)
  await expect(page.locator('.review-summary')).toContainText('Просмотрено треков2')
})

test('25 decisions apply, reload continues at card 26, and the next apply contains only new decisions', async ({ page }) => {
  await reviewWithoutAudio(page, 'Большая коллекция')
  await page.getByRole('button', { name: 'Убрать', exact: false }).click()
  for (let i = 1; i < 25; i++) await page.getByRole('button', { name: 'Оставить', exact: false }).click()
  await expect(page.getByRole('heading', { name: 'Сессия завершена.' })).toBeVisible()
  await page.getByRole('button', { name: /Проверить решения/ }).first().click()
  await expect(page.locator('.preview-list li')).toHaveCount(1)
  const expectedCount = Number((await page.locator('.preview-heading > p').innerText()).match(/останется (\d+)/)?.[1])
  await page.getByRole('button', { name: 'Применить в демо' }).click()
  await page.getByRole('button', { name: 'Продолжить разбор' }).click()
  const next = await page.locator('.track-details h2').innerText()
  await expect(page.locator('.review-summary')).toContainText('Просмотрено треков25')
  await expect(page.getByRole('button', { name: /Отменить решение/ })).toBeDisabled()
  await expect(page.locator('.save-status')).toHaveText('Решения сохранены на этом устройстве')
  await page.reload()
  await page.getByRole('button', { name: /Большая коллекция/ }).click()
  await page.getByRole('button', { name: /Начать разбор/ }).click()
  await expect(page.locator('.track-details h2')).toHaveText(next)
  await expect(page.locator('.review-summary dd').first()).toHaveText(expectedCount.toLocaleString('ru-RU'))
  await page.getByRole('button', { name: 'Продолжить без звука' }).click()
  await page.getByRole('button', { name: 'Убрать', exact: false }).click()
  await page.getByRole('button', { name: /Проверить решения/ }).click()
  await expect(page.locator('.preview-list li')).toHaveCount(1)
  await page.getByRole('button', { name: 'Применить в демо' }).click()
  await expect(page.getByRole('heading', { name: 'Результат совпал с планом.' })).toBeVisible()
})

test('blocked IndexedDB reports volatile decisions while keeping demo usable', async ({ page }) => {
  await page.addInitScript(() => Object.defineProperty(window, 'indexedDB', { get() { throw new Error('storage blocked') } }))
  await reviewWithoutAudio(page)
  await expect(page.getByRole('alert')).toContainText('только до перезагрузки')
  await page.getByRole('button', { name: 'Оставить', exact: false }).click()
  await expect(page.locator('.save-status')).toHaveText('Решения пока только в этой вкладке')
  await expect(page.locator('.review-summary')).toContainText('Просмотрено треков1')
})

test('clearing local demo data restores fixtures without touching Spotify', async ({ page }) => {
  await reviewWithoutAudio(page)
  await page.getByRole('button', { name: 'Убрать', exact: false }).click()
  await expect(page.locator('.save-status')).toHaveText('Решения сохранены на этом устройстве')
  page.once('dialog', (dialog) => dialog.accept())
  await page.getByRole('button', { name: 'Очистить локальные демо-данные' }).click()
  await expect(page.getByRole('button', { name: /Ночная прогулка/ })).toContainText('8 записей')
  await page.getByRole('button', { name: /Начать разбор/ }).click()
  await expect(page.getByRole('button', { name: /Отменить решение/ })).toBeDisabled()
})

test('volatile decisions survive switching playlists within the same tab', async ({ page }) => {
  await page.addInitScript(() => Object.defineProperty(window, 'indexedDB', { get() { throw new Error('storage blocked') } }))
  await reviewWithoutAudio(page)
  await page.getByRole('button', { name: 'Убрать', exact: false }).click()
  await expect(page.locator('.session-progress > span')).toContainText('2 / 6')
  const next = await page.locator('.track-details h2').innerText()
  await page.getByRole('button', { name: 'Другой плейлист' }).click()
  await page.getByRole('button', { name: /Особенные записи/ }).click()
  await page.getByRole('button', { name: /Начать разбор/ }).click()
  await page.getByRole('button', { name: 'Другой плейлист' }).click()
  await page.getByRole('button', { name: /Ночная прогулка/ }).click()
  await page.getByRole('button', { name: /Начать разбор/ }).click()
  await expect(page.locator('.track-details h2')).toHaveText(next)
  await expect(page.locator('.review-summary')).toContainText('Просмотрено треков1')
  await expect(page.locator('.review-summary')).toContainText('Групп на удаление1')
})

test('a stale tab cannot apply after another tab saved newer decisions', async ({ page, context }) => {
  await reviewWithoutAudio(page)
  const other = await context.newPage()
  await reviewWithoutAudio(other)
  await other.getByRole('button', { name: 'Оставить', exact: false }).click()
  await expect(other.locator('.save-status')).toHaveText('Решения сохранены на этом устройстве')
  await page.getByRole('button', { name: 'Убрать', exact: false }).click()
  await expect(page.getByRole('alert')).toContainText('другой вкладке')
  await page.getByRole('button', { name: /Проверить решения/ }).click()
  await expect(page.getByRole('alert').first()).toContainText('другой вкладке')
  await expect(page.getByRole('button', { name: 'Применить в демо' })).not.toBeVisible()
  await other.reload()
  await expect(other.getByRole('button', { name: /Ночная прогулка/ })).toContainText('8 записей')
  await other.close()
})

test('a previously saved tab revalidates revision before applying after another tab edits its draft', async ({ page, context }) => {
  await reviewWithoutAudio(page)
  await page.getByRole('button', { name: 'Убрать', exact: false }).click()
  await expect(page.locator('.save-status')).toHaveText('Решения сохранены на этом устройстве')
  const other = await context.newPage()
  await reviewWithoutAudio(other)
  await other.getByRole('button', { name: /Отменить решение/ }).click()
  await other.getByRole('button', { name: 'Оставить', exact: false }).click()
  await expect(other.locator('.save-status')).toHaveText('Решения сохранены на этом устройстве')
  await page.getByRole('button', { name: /Проверить решения/ }).click()
  await expect(page.getByRole('alert').first()).toContainText('другой вкладке')
  await expect(page.getByRole('button', { name: 'Применить в демо' })).not.toBeVisible()
  await other.reload()
  await expect(other.getByRole('button', { name: /Ночная прогулка/ })).toContainText('8 записей')
  await other.close()
})
